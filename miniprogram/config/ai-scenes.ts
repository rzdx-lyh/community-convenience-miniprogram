/**
 * 问题归一化：去掉结尾标点与空白。
 * 用户手打很少带「？」，全等匹配会大面积落空（原型已踩过）。
 */
export function normQuestion(q: string): string {
  return String(q ?? '').replace(/[\s?？!！。.,，、~]+$/g, '').trim();
}

/**
 * 本地问答库查询（纯函数）：
 *   ① 归一化后精确匹配 → ② 补「？」再匹配 → ③ 双向包含兜底（≥4 字）。
 * 命中返回条目，未命中返回 null（调用方再决定走云还是转人工）。
 */
export function lookupAnswer(q: string): QaEntry | null {
  const key = normQuestion(q);
  if (!key) return null;
  if (QA_BANK[key]) return QA_BANK[key];
  if (QA_BANK[`${key}？`]) return QA_BANK[`${key}？`];
  let hit: QaEntry | null = null;
  Object.keys(QA_BANK).forEach((raw) => {
    if (hit) return;
    const kk = normQuestion(raw);
    if (key.length >= 4 && kk.length >= 4 && (kk.indexOf(key) >= 0 || key.indexOf(kk) >= 0)) {
      hit = QA_BANK[raw];
    }
  });
  return hit;
}

